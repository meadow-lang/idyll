#!/usr/bin/env python3
"""Turn the output of `cargo run --release -- tables` into the Haskell module
System.Console.Rustyline.Internal.Unicode.Tables.

The Rust side (gen/src/main.rs) links the exact `unicode-width` and
`unicode-segmentation` versions rustyline depends on and dumps their data as
maximal runs, so the Haskell port reproduces their answers bit for bit.
See gen/README.md for the full regeneration recipe.
"""
import sys
from collections import defaultdict

GC_NAMES = {
    "GC_Any": "GCAny", "GC_CR": "GCCR", "GC_Control": "GCControl",
    "GC_Extend": "GCExtend", "GC_Extended_Pictographic": "GCExtendedPictographic",
    "GC_InCB_Consonant": "GCInCBConsonant", "GC_L": "GCL", "GC_LF": "GCLF",
    "GC_LV": "GCLV", "GC_LVT": "GCLVT", "GC_Prepend": "GCPrepend",
    "GC_Regional_Indicator": "GCRegionalIndicator", "GC_SpacingMark": "GCSpacingMark",
    "GC_T": "GCT", "GC_V": "GCV", "GC_ZWJ": "GCZWJ",
}
GC_ORDER = list(GC_NAMES)

rows = defaultdict(list)
for line in open(sys.argv[1]):
    tag, lo, hi, val = line.split()
    rows[tag].append((int(lo, 16), int(hi, 16), val))

def ints(xs, indent="      "):
    """Format a list literal, wrapped to roughly 78 columns."""
    lines, cur = [], ""
    for x in xs:
        piece = str(x)
        if cur and len(indent) + len(cur) + len(piece) + 2 > 78:
            lines.append(cur + ",")
            cur = piece
        else:
            cur = piece if not cur else cur + ", " + piece
    lines.append(cur)
    body = ("\n" + indent).join(lines)
    return "[ " + body + "\n" + indent[:-2] + "]"

def table(name, doc, tag, conv):
    rs = rows[tag]
    return (f"-- | {doc}\n{name} :: RangeTable\n{name} =\n  mkRangeTable\n"
            f"    {ints([r[0] for r in rs])}\n"
            f"    {ints([r[1] for r in rs])}\n"
            f"    {ints([conv(r[2]) for r in rs])}\n")

out = ['''-- | GENERATED by gen/gen_tables.py from unicode-width 0.2.2 and
--   unicode-segmentation 1.13.3 (Unicode 17.0.0), plus the Rust std\n--   char predicates rustyline uses. Do not edit by hand.
module System.Console.Rustyline.Internal.Unicode.Tables
  ( widthTable,
    nonTransparentZeroWidthTable,
    emojiPresentationTable,
    textPresentationTable,
    emojiModifierBaseTable,
    graphemeCatTable,
    incbExtendTable,
    incbLinkerTable,
    alphanumericTable,
    whitespaceTable,
  )
where

import System.Console.Rustyline.Internal.Unicode.RangeTable
''']
ident = lambda v: int(v)
out.append(table("widthTable", "Raw 2-bit width class per code point (3 = needs special handling); default 1.", "W", ident))
out.append(table("nonTransparentZeroWidthTable", "Zero-width code points that are not Joining_Type=Transparent.", "NTZ", ident))
out.append(table("emojiPresentationTable", "Code points that start an emoji presentation sequence.", "EP", ident))
out.append(table("textPresentationTable", "Non-ideographic code points that start a text presentation sequence.", "TP", ident))
out.append(table("emojiModifierBaseTable", "Emoji_Modifier_Base code points.", "EMB", ident))
out.append(table("graphemeCatTable", "Grapheme_Cluster_Break category (index into GraphemeCat); default Any.", "GC", lambda v: GC_ORDER.index(v)))
out.append(table("incbExtendTable", "InCB=Extend code points.", "ICE", ident))
out.append(table("incbLinkerTable", "InCB=Linker code points.", "ICL", ident))
out.append(table("alphanumericTable", "Rust's char::is_alphanumeric.", "ALNUM", ident))
out.append(table("whitespaceTable", "Rust's char::is_whitespace.", "WS", ident))
sys.stdout.write("\n".join(out))
